"""
src/reporting.py
----------------
Generates executive advisory reports for farmers and agricultural officers.
Supports Markdown, HTML view, CSV export, and download payloads.
"""

import io
from typing import Dict, Any, List
import pandas as pd


def generate_farmer_report_text(report_data: Dict[str, Any]) -> str:
    """
    Builds a clean, structured text report for display and export.
    """
    farmer = report_data.get("farmer", {})
    soil = report_data.get("soil", {})
    current = report_data.get("current_crop", {})
    top_crops = report_data.get("top_alternatives", [])
    water = report_data.get("water_and_climate", {})
    missing_info = report_data.get("missing_info_and_uncertainty", [])
    next_steps = report_data.get("practical_next_steps", [])

    lines = []
    lines.append("=" * 65)
    lines.append("           🌾 FASAL AI — FARM ADVISORY REPORT")
    lines.append("=" * 65)
    lines.append(f"Farmer Name:   {farmer.get('name', 'Farmer')}")
    lines.append(f"Location:      {farmer.get('village', 'Village')}, {farmer.get('district', 'District')}, {farmer.get('state', 'State')}")
    lines.append(f"Field Holding: {farmer.get('area_acres', 2.0)} Acres ({round(farmer.get('area_acres', 2.0)*0.4047, 2)} Hectares)")
    lines.append("-" * 65)

    lines.append("\n[1] SOIL HEALTH ASSESSMENT")
    lines.append(f"  • Overall Health Index: {soil.get('overall_health_score', 'N/A')}/100 ({soil.get('health_rating', 'N/A')})")
    lines.append(f"  • Soil Texture:         {soil.get('texture', 'Loam')}")
    lines.append(f"  • pH:                   {soil.get('ph', 'N/A')}")
    lines.append(f"  • Available NPK:        N: {soil.get('n', 'N/A')} kg/ha | P: {soil.get('p', 'N/A')} kg/ha | K: {soil.get('k', 'N/A')} kg/ha")
    if soil.get("recommended_amendments"):
        lines.append("  • Soil Amendments:")
        for am in soil["recommended_amendments"][:3]:
            lines.append(f"    - {am}")

    lines.append("\n[2] CURRENT CROP BASELINE")
    lines.append(f"  • Crop:                 {current.get('crop', 'N/A')}")
    lines.append(f"  • Estimated Yield:      {current.get('yield_q_acre', 'N/A')} q/acre ({current.get('yield_tonnes_ha', 'N/A')} t/ha)")
    lines.append(f"  • Estimated Net Profit: ₹{current.get('net_profit', 0):,.0f} (₹{current.get('net_profit_acre', 0):,.0f}/acre)")
    lines.append(f"  • Water Requirement:    {current.get('water_liters', 0):,.0f} Liters")

    lines.append("\n[3] TOP RECOMMENDED ALTERNATIVES")
    for i, alt in enumerate(top_crops, 1):
        lines.append(f"  Option #{i}: {alt.get('crop', 'N/A')} ({alt.get('season', 'N/A')})")
        lines.append(f"    - Suitability Score:   {alt.get('suitability_score', 'N/A')}%")
        lines.append(f"    - Est. Yield:          {alt.get('yield_q_acre', 'N/A')} q/acre ({alt.get('yield_tonnes_ha', 'N/A')} t/ha)")
        lines.append(f"    - Est. Net Profit:     ₹{alt.get('net_profit', 0):,.0f} (₹{alt.get('net_profit_acre', 0):,.0f}/acre)")
        lines.append(f"    - Net Profit Gain:     +₹{alt.get('profit_delta_rs', 0):,.0f} vs current")
        lines.append(f"    - Water Conserved:     {alt.get('water_saved_pct', 0):.0f}%")
        lines.append(f"    - Water Cap Status:    {'✅ Within Cap' if alt.get('is_within_cap') else '⚠️ Exceeds Cap'}")

    lines.append("\n[4] WATER & SEASONAL CONSIDERATIONS")
    lines.append(f"  • Irrigation Cap:       {water.get('water_cap_mm', 600)} mm")
    lines.append(f"  • Recommended Method:   {water.get('recommended_irrigation', 'Drip')}")
    lines.append(f"  • Weather Scenario:     {water.get('weather_scenario', 'Normal')}")

    if missing_info:
        lines.append("\n[5] MISSING INFORMATION & UNCERTAINTY")
        for m in missing_info:
            lines.append(f"  • {m}")

    if next_steps:
        lines.append("\n[6] PRACTICAL NEXT STEPS")
        for s in next_steps:
            lines.append(f"  1. {s}")

    lines.append("\n" + "=" * 65)
    lines.append("Generated by FASAL AI (PySustain CSE Hackathon 2026)")
    lines.append("=" * 65)

    return "\n".join(lines)


def generate_report_csv_bytes(report_data: Dict[str, Any]) -> bytes:
    """
    Serializes report recommendations into downloadable CSV format.
    """
    top_crops = report_data.get("top_alternatives", [])
    current = report_data.get("current_crop", {})

    rows = []
    # Add current crop
    rows.append({
        "Status": "Current Crop",
        "Crop": current.get("crop"),
        "Season": current.get("season"),
        "Yield_q_acre": current.get("yield_q_acre"),
        "Yield_tonnes_ha": current.get("yield_tonnes_ha"),
        "Gross_Revenue_INR": current.get("gross_revenue"),
        "Total_Cost_INR": current.get("total_cost"),
        "Net_Profit_INR": current.get("net_profit"),
        "Net_Profit_Acre_INR": current.get("net_profit_acre"),
        "Profit_Delta_INR": 0,
        "Water_Liters": current.get("water_liters"),
        "Water_Saved_Pct": 0.0,
        "Suitability_Score": current.get("suitability_score", 100.0)
    })

    # Add recommendations
    for i, alt in enumerate(top_crops, 1):
        rows.append({
            "Status": f"Recommended #{i}",
            "Crop": alt.get("crop"),
            "Season": alt.get("season"),
            "Yield_q_acre": alt.get("yield_q_acre"),
            "Yield_tonnes_ha": alt.get("yield_tonnes_ha"),
            "Gross_Revenue_INR": alt.get("gross_revenue"),
            "Total_Cost_INR": alt.get("total_cost"),
            "Net_Profit_INR": alt.get("net_profit"),
            "Net_Profit_Acre_INR": alt.get("net_profit_acre"),
            "Profit_Delta_INR": alt.get("profit_delta_rs"),
            "Water_Liters": alt.get("water_liters"),
            "Water_Saved_Pct": alt.get("water_saved_pct"),
            "Suitability_Score": alt.get("suitability_score")
        })

    df = pd.DataFrame(rows)
    return df.to_csv(index=False).encode("utf-8")

